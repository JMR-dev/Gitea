#!/usr/bin/env bash
# A throwaway VM to rehearse the playbook (vm/ansible) on before it meets prod:
# `make rehearsal-up`, then `make vm-apply VM=gitea-rehearsal` (and
# `make ci-vm-apply VM=gitea-rehearsal` for cb-infra's path), then
# `make rehearsal-down`, which deletes everything this created.
#
#   scripts/rehearsal.sh up            a blank AlmaLinux 10 VM, as a replacement would be
#   scripts/rehearsal.sh up --legacy   the same, booted by the pre-Ansible vm/bootstrap.sh
#                                      (the rollback path), with its secret names pointed
#                                      at the rehearsal's own
#   scripts/rehearsal.sh down
#
# Like prod (infra/pkg/compute) but cut off from it:
#   - its own service account, which reads only gitea-rehearsal-* secrets
#     (created empty here; the playbook generates them, as it would for a
#     new project), the image repository, and in --legacy the config bucket;
#   - domain rehearsal.invalid, so Caddy never gets a certificate and no DNS
#     record is touched, and no backup bucket;
#   - a blank 10 GB data disk, never prod data;
#   - a network tag of its own that opens only SSH from IAP -- prod's tag
#     would also open 80/443/2222 to the internet.
set -euo pipefail

PROJECT=${PROJECT:-gitea-496920}
ZONE=${ZONE:-us-east1-b}
REGION=${REGION:-us-east1}
PROD_VM=${PROD_VM:-gitea-vm}
VM=gitea-rehearsal
NAME=gitea-rehearsal
SA=${NAME}@${PROJECT}.iam.gserviceaccount.com
PREFIX=gitea-rehearsal
SECRETS=(secret-key internal-token oauth2-jwt-secret lfs-jwt-secret)
LEGACY_REV=${LEGACY_REV:-c5df517}  # a main commit that still has vm/bootstrap.sh
g() { gcloud --project="${PROJECT}" --quiet "$@"; }

up() {
    local legacy=0
    [[ "${1:-}" == "--legacy" ]] && legacy=1

    g iam service-accounts describe "${SA}" >/dev/null 2>&1 \
        || g iam service-accounts create "${NAME}" --display-name="Gitea rehearsal VM (throwaway; scripts/rehearsal.sh)"
    # A new account takes a few seconds to be visible to policy bindings.
    local i
    for i in 1 2 3 4 5 6 7 8 9; do
        g projects add-iam-policy-binding "${PROJECT}" --member="serviceAccount:${SA}" \
            --role=roles/logging.logWriter --condition=None >/dev/null 2>&1 && break
        (( i < 9 )) || { echo "cannot bind ${SA}" >&2; exit 1; }
        sleep 10
    done
    g artifacts repositories add-iam-policy-binding gitea --location="${REGION}" \
        --member="serviceAccount:${SA}" --role=roles/artifactregistry.reader >/dev/null
    for s in "${SECRETS[@]}"; do
        g secrets describe "${PREFIX}-${s}" >/dev/null 2>&1 \
            || g secrets create "${PREFIX}-${s}" --replication-policy=automatic --labels=purpose=rehearsal >/dev/null
        for role in roles/secretmanager.secretAccessor roles/secretmanager.secretVersionAdder; do
            g secrets add-iam-policy-binding "${PREFIX}-${s}" --member="serviceAccount:${SA}" --role="${role}" >/dev/null
        done
    done
    if (( legacy )); then
        g storage buckets add-iam-policy-binding "gs://${PROJECT}-gitea-config" \
            --member="serviceAccount:${SA}" --role=roles/storage.objectViewer >/dev/null
        # The old bash generates a missing Gitea secret only once the image is
        # on the VM, which it never is on a first boot -- so it would render
        # nothing. Prod's secrets always exist; give the rehearsal's values
        # first, generated by the prod image here.
        local image
        image=$(g compute instances describe "${PROD_VM}" --zone="${ZONE}" \
            --format='value(metadata.items.filter(key:image-gitea).extract(value).flatten())')
        gcloud auth print-access-token | podman login -u oauth2accesstoken --password-stdin "${REGION}-docker.pkg.dev" >/dev/null
        for s in secret-key:SECRET_KEY internal-token:INTERNAL_TOKEN oauth2-jwt-secret:JWT_SECRET lfs-jwt-secret:LFS_JWT_SECRET; do
            if ! g secrets versions access latest --secret="${PREFIX}-${s%%:*}" >/dev/null 2>&1; then
                podman run --rm "${image}" generate secret "${s#*:}" \
                    | g secrets versions add "${PREFIX}-${s%%:*}" --data-file=- >/dev/null
            fi
        done
    fi

    g compute firewall-rules describe "${NAME}-iap-ssh" >/dev/null 2>&1 \
        || g compute firewall-rules create "${NAME}-iap-ssh" --network=gitea-vpc --direction=INGRESS \
            --allow=tcp:22 --source-ranges=35.235.240.0/20 --target-tags="${NAME}" >/dev/null

    # Prod's metadata, less what must not carry over, plus the rehearsal's own.
    local md
    md=$(mktemp -d)
    trap 'rm -rf "${md}"' RETURN
    g compute instances describe "${PROD_VM}" --zone="${ZONE}" --format=json | python3 -c '
import json, os, sys
md = sys.argv[1]
items = {i["key"]: i.get("value", "") for i in json.load(sys.stdin)["metadata"].get("items", [])}
for k in ("startup-script", "config-hash"):
    items.pop(k, None)
items.update({"domain": "rehearsal.invalid", "backup-bucket": "", "gitea-secret-prefix": "gitea-rehearsal"})
for k, v in items.items():
    with open(os.path.join(md, k), "w") as f:
        f.write(v)
' "${md}"
    if (( legacy )); then
        # The old startup script reads fixed secret names; point them at ours.
        git show "${LEGACY_REV}:vm/bootstrap.sh" | sed -E \
            -e "s/(--secret=|fetch_or_create_secret )gitea-/\1${PREFIX}-/g" > "${md}/startup-script"
        grep -q "${PREFIX}-secret-key" "${md}/startup-script" || { echo "secret rename failed" >&2; exit 1; }
    fi
    local from=()
    for f in "${md}"/*; do from+=("$(basename "${f}")=${f}"); done

    g compute instances create "${VM}" --zone="${ZONE}" --machine-type=e2-small \
        --image-family=almalinux-10 --image-project=almalinux-cloud \
        --boot-disk-size=20GB --boot-disk-type=pd-balanced \
        --create-disk="name=${VM}-data,size=10GB,type=pd-balanced,device-name=gitea-data,auto-delete=yes" \
        --subnet=gitea-subnet --tags="${NAME}" \
        --service-account="${SA}" --scopes=cloud-platform \
        --shielded-secure-boot --shielded-vtpm --shielded-integrity-monitoring \
        --labels=app=gitea-rehearsal \
        --metadata-from-file="$(IFS=,; echo "${from[*]}")"
    echo "rehearsal VM ${VM} is up$( (( legacy )) && echo ' (booted by the legacy vm/bootstrap.sh)')"
}

down() {
    g compute instances delete "${VM}" --zone="${ZONE}" --delete-disks=all 2>/dev/null || true
    g compute disks delete "${VM}-data" --zone="${ZONE}" 2>/dev/null || true
    g compute firewall-rules delete "${NAME}-iap-ssh" 2>/dev/null || true
    for s in "${SECRETS[@]}"; do g secrets delete "${PREFIX}-${s}" 2>/dev/null || true; done
    g storage buckets remove-iam-policy-binding "gs://${PROJECT}-gitea-config" \
        --member="serviceAccount:${SA}" --role=roles/storage.objectViewer >/dev/null 2>&1 || true
    g artifacts repositories remove-iam-policy-binding gitea --location="${REGION}" \
        --member="serviceAccount:${SA}" --role=roles/artifactregistry.reader >/dev/null 2>&1 || true
    g projects remove-iam-policy-binding "${PROJECT}" --member="serviceAccount:${SA}" \
        --role=roles/logging.logWriter --condition=None >/dev/null 2>&1 || true
    g iam service-accounts delete "${SA}" 2>/dev/null || true
    echo "rehearsal resources deleted"
}

case "${1:-}" in
    up) shift; up "$@" ;;
    down) down ;;
    *) echo "usage: $0 up [--legacy] | down" >&2; exit 2 ;;
esac
